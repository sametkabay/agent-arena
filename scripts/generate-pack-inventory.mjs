// Scans public/assets/packs for *.glb and writes packInventory.generated.ts
// Run: node scripts/generate-pack-inventory.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(rootDir, "..");
const packsRoot = path.join(repoRoot, "public", "assets", "packs");
const outFile = path.join(repoRoot, "src", "lib", "assets", "packInventory.generated.ts");

/** @type {{ pack: string; file: string }[]} */
const entries = [];

for (const dirent of fs.readdirSync(packsRoot, { withFileTypes: true })) {
  if (!dirent.isDirectory()) continue;
  const pack = dirent.name;
  const dir = path.join(packsRoot, pack);
  for (const name of fs.readdirSync(dir).sort((a, b) => a.localeCompare(b))) {
    if (!name.toLowerCase().endsWith(".glb")) continue;
    entries.push({ pack, file: name });
  }
}

const body = `/** Auto-generated by scripts/generate-pack-inventory.mjs - do not edit. */
export interface PackGlbEntry {
  pack: string;
  file: string;
}

export const PACK_GLB_INVENTORY: readonly PackGlbEntry[] = ${JSON.stringify(entries, null, 2)} as const;
`;

fs.writeFileSync(outFile, body, "utf8");
console.log(`Wrote ${entries.length} entries → ${path.relative(repoRoot, outFile)}`);
